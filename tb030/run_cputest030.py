#!/usr/bin/env python3
"""Replay WinUAE cputest 68030 corpus slices on the AP68030 (070) core.

  ./run_cputest.py CORPUS                     smoke set (one slice per group)
  ./run_cputest.py CORPUS --full              every slice
  ./run_cputest.py CORPUS --full --group AE --instruction 'Bcc.*'
  ./run_cputest.py CORPUS --full --group Basic --slice 0001 --round-limit 500

CORPUS is the 68030 corpus directory (68030_<group>/<instruction>/NNNN.dat.gz,
data version 20), e.g. /home/adam/ap68030/cputest030/data.  Jobs are
generated by tools/cputest030/replay_gen.py (AP68030's generator, APR2), run
by tb030/tb_cputest030.sv (build_cputest030.sh), one simulator process per
slice, in parallel.  The FPU groups are not run (no FPU); the IRQ groups need
the v20 interrupt model of AP68030's bench, not ported yet (--group IRQ runs
them anyway).
"""

import argparse
import concurrent.futures
import fnmatch
import gzip
import hashlib
import json
import os
import re
import struct
import subprocess
import sys
import threading
import time
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path.insert(0, str(REPO / "tools" / "cputest030"))
from replay_gen import generate  # noqa: E402

OBJ = Path(os.environ.get("WORK", REPO / "obj030cpt"))
SIM = Path(os.environ.get("CPUTEST_SIM", OBJ / "obj_cputest" / "tb_cputest"))
MON = Path(os.environ.get("CPUTEST_MON", OBJ / "cputest_mon030.bin"))

# group directories are 68030_<name>; the integer groups only
INTEGER = ["AE", "Basic", "Default", "FFEXT_DST", "FFEXT_SRC", "IRQ", "JITLM",
           "ODD_EXC", "ODD_IRQ", "ODD_STK"]
NOT_DEFAULT = ["IRQ", "ODD_IRQ"]
SMOKE = [("Default", "DIVS.W", "0001"), ("Basic", "ABCD.B", "0001"),
         ("AE", "BSR.B", "0001"), ("ODD_EXC", "ANDSR.W", "0001"),
         ("FFEXT_SRC", "MOVE.L", "0001"), ("ODD_STK", "BSR.W", "0001")]


def corpus_root(src: Path, work: Path) -> Path:
    for cand in (src, src / "data"):
        if any(cand.glob("68030_*")):
            return cand
    raise SystemExit("no 68030_* groups under %s" % src)


def unpack_daz(daz: Path, cache: Path) -> Path:
    key = hashlib.sha256(daz.read_bytes()).hexdigest()[:16]
    target = cache / key
    if (target / ".complete").exists():
        return target
    data = daz.read_bytes()
    target.mkdir(parents=True, exist_ok=True)
    off = index = 0
    while off + 8 <= len(data) and data[off:off + 4] == b"\xafMRG":
        length = struct.unpack(">I", data[off + 4:off + 8])[0]
        if length == 0:
            break
        (target / ("%04d.dat" % index)).write_bytes(
            gzip.decompress(data[off + 8:off + 8 + length]))
        off += 8 + length
        index += 1
    (target / ".complete").write_text(str(index))
    return target


def image(group_dir: Path, name: str, cache: Path) -> Path:
    gz = group_dir / (name + ".gz")
    src = gz if gz.exists() else group_dir / name
    key = hashlib.sha256(src.read_bytes()).hexdigest()[:16]
    out = cache / (name + "." + key)
    if not out.exists():
        # parallel slices share the cache: publish the file atomically
        cache.mkdir(parents=True, exist_ok=True)
        data = gzip.open(src).read() if src.suffix == ".gz" else src.read_bytes()
        tmp = out.with_name(out.name + ".%d.%d" % (os.getpid(), threading.get_ident()))
        tmp.write_bytes(data)
        os.replace(tmp, out)
    return out


def match(v, pats):
    return not pats or any(fnmatch.fnmatchcase(v, p) for p in pats)


def discover(root: Path, args):
    out = []
    for hdr in sorted(root.glob("68030_*/*/0000.dat")):
        group = hdr.parent.parent.name[6:]
        instr = hdr.parent.name
        if group not in INTEGER:
            continue
        if not args.group and group in NOT_DEFAULT:
            continue
        if not match(group, args.group) or not match(instr, args.instruction):
            continue
        cache = args.work / "unpacked" / group / instr
        for dat in sorted(hdr.parent.glob("[0-9][0-9][0-9][0-9].dat*")):
            num = dat.name[:4]
            if num == "0000" or not match(num, args.slice):
                continue
            if not args.full and (group, instr, num) not in SMOKE:
                continue
            if dat.suffix == ".gz":
                cache.mkdir(parents=True, exist_ok=True)
                plain = cache / (num + ".dat")
                if not plain.exists():
                    plain.write_bytes(gzip.decompress(dat.read_bytes()))
                dat = plain
            out.append(dict(group=group, instr=instr, slice=num, header=hdr,
                            data=dat, gdir=hdr.parent.parent))
    return out


def run(item, args):
    name = "%s--%s--%s" % (item["group"], item["instr"].replace("/", "_"), item["slice"])
    job = args.work / "jobs" / (name + ".apr2")
    log = args.work / "logs" / (name + ".log")
    job.parent.mkdir(parents=True, exist_ok=True)
    log.parent.mkdir(parents=True, exist_ok=True)
    t0 = time.monotonic()
    try:
        generate(str(item["header"]), str(item["data"]), str(job), args.round_limit)
        cmd = [str(SIM), "+job=%s" % job, "+mon=%s" % MON,
               "+lmem=%s" % image(item["gdir"], "lmem.dat", args.work / "images"),
               "+tmem=%s" % image(item["gdir"], "tmem.dat", args.work / "images")]
        cmd += args.plusarg
        p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                           text=True, timeout=args.timeout)
        out = p.stdout
        status = "pass" if "ALL TESTS PASSED" in out else "fail"
    except subprocess.TimeoutExpired as e:
        out = (e.stdout or b"").decode() if isinstance(e.stdout, bytes) else (e.stdout or "")
        status = "timeout"
    except Exception as e:  # report and continue with the other slices
        out = repr(e)
        status = "error"
    log.write_text(out)
    if not args.keep_jobs and job.exists():
        job.unlink()
    summ = [l for l in out.splitlines() if l.startswith("cputest replay")]
    first = [l for l in out.splitlines() if l.startswith(("MISMATCH", "FAIL"))][:1]
    return dict(name=name, status=status, seconds=time.monotonic() - t0,
                summary=summ[0] if summ else "", first=first[0] if first else "")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("corpus", type=Path)
    ap.add_argument("--work", type=Path, default=OBJ / "cputest")
    ap.add_argument("--full", action="store_true")
    ap.add_argument("--group", action="append", default=[])
    ap.add_argument("--instruction", action="append", default=[])
    ap.add_argument("--slice", action="append", default=[])
    ap.add_argument("--round-limit", type=int, default=None)
    ap.add_argument("--sample", type=lambda s: tuple(int(x) for x in s.split(":")),
                    default=None, metavar="FLOOR:STRIDE",
                    help="every round up to FLOOR per slice, then every STRIDE-th "
                         "(e.g. 300:24, about 6%% of the full corpus's rounds)")
    ap.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2) // 2))
    ap.add_argument("--timeout", type=int, default=3600)
    ap.add_argument("--keep-jobs", action="store_true")
    ap.add_argument("--plusarg", action="append", default=[])
    ap.add_argument("--known", type=Path, default=None,
                    help="known oracle deviations (tb/cputest_known.txt): a slice "
                         "whose first mismatch matches one is reported KNOWN")
    ap.add_argument("--skip-log", type=Path, action="append", default=[],
                    help="skip slices reported PASS in this earlier runner output")
    args = ap.parse_args()
    args.work.mkdir(parents=True, exist_ok=True)
    if not SIM.exists() or not MON.exists():
        raise SystemExit("build the bench first: tb030/build_cputest030.sh")
    root = corpus_root(args.corpus, args.work)
    items = discover(root, args)
    passed = set()
    for lg in args.skip_log:
        for line in lg.read_text(errors="replace").splitlines():
            f = line.split()
            if len(f) >= 2 and f[0] == "PASS":
                passed.add(f[1])
    if passed:
        items = [it for it in items if "%s--%s--%s" % (
            it["group"], it["instr"].replace("/", "_"), it["slice"]) not in passed]
    known = []
    if args.known:
        for line in args.known.read_text().splitlines():
            if line.strip() and not line.lstrip().startswith("#"):
                f = line.split()
                known.append((f[0], re.compile(f[1]), f[2] if len(f) > 2 else ""))
    print("%d slices" % len(items), flush=True)
    results = []
    with concurrent.futures.ThreadPoolExecutor(args.jobs) as ex:
        for r in ex.map(lambda it: run(it, args), items):
            if r["status"] != "pass" and known:
                # every mismatch of the slice must be a known one, not just its
                # first (the slice's log has them all)
                lg = args.work / "logs" / (r["name"] + ".log")
                bad, seen = [], set()
                for l in (lg.read_text(errors="replace").splitlines()
                          if lg.exists() else [r["first"]]):
                    # each round's first mismatch (the rest follow from it)
                    f = l.split()
                    if (l.startswith("MISMATCH") or l.startswith("FAIL j")) and len(f) > 1:
                        if f[1] not in seen:
                            seen.add(f[1])
                            bad.append(l)
                whys = set()
                for l in bad or [r["first"]]:
                    m = [why for g, rx, why in known
                         if fnmatch.fnmatchcase(r["name"], g) and rx.search(l)]
                    if not m:
                        whys = None
                        break
                    whys.add(m[0])
                if whys:
                    r["status"] = "known"
                    r["first"] = "[%s] %s" % (",".join(sorted(whys)), r["first"])
            results.append(r)
            print("%-6s %-44s %s %s" % (r["status"].upper(), r["name"], r["summary"],
                                        ("| " + r["first"]) if r["status"] != "pass" else ""),
                  flush=True)
    npass = sum(r["status"] == "pass" for r in results)
    nknown = sum(r["status"] == "known" for r in results)
    print("PASSED %d / %d slices" % (npass, len(results)) +
          (" (%d known oracle deviations, %d failing)" % (nknown, len(results) - npass - nknown)
           if args.known else ""))
    (args.work / "summary.json").write_text(json.dumps(results, indent=1))
    sys.exit(0 if npass + nknown == len(results) else 1)


if __name__ == "__main__":
    main()
